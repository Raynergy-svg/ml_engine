def test_atomic_rename_failure_logs_no_partial_file(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    caplog,
) -> None:
    """Simulated os.replace failure -> ERROR log, snapshot.md unchanged from
    previous content, heartbeat reflects the failure."""
    _seed_minimal_state(tmp_path)
    writer = BriefingSnapshotWriter(project_root=tmp_path)

    # First write succeeds normally — we need a baseline snapshot to assert
    # "unchanged from previous content" against.
    assert writer.write_now(trigger="first") is True
    snap_path = tmp_path / ".claude" / "brain" / "snapshot.md"
    baseline_content = snap_path.read_text()
    baseline_mtime = snap_path.stat().st_mtime

    # Mutate state so the diff detector WOULD trigger a rewrite, then break
    # os.replace via monkeypatch (this is environmental injection, NOT a mock
    # of code under test).
    _write_json(tmp_path / ".claude" / "state.json", {
        "halted": True,  # change so diff fires
        "mode": "demo",
        "scan_cycle_count": 99,
    })
    # Wrap os.replace so it ONLY fails on the snapshot.md target. The
    # heartbeat write also uses os.replace and must still succeed so we
    # can read it back to confirm the failure was recorded.
    real_replace = os.replace
    snap_path_str = str(snap_path)

    def selective_boom(src, dst, *args, **kwargs):  # noqa: ANN001
        if str(dst) == snap_path_str:
            raise OSError(28, "No space left on device")
        return real_replace(src, dst, *args, **kwargs)

    monkeypatch.setattr(
        "src.scanner.automation.briefing_snapshot.os.replace",
        selective_boom,
    )

    with caplog.at_level(logging.ERROR, logger="src.scanner.automation.briefing_snapshot"):
        ok = writer.write_now(trigger="should_fail")

    assert ok is False
    # snapshot.md must be unchanged (atomic semantics — no partial file)
    assert snap_path.read_text() == baseline_content
    assert snap_path.stat().st_mtime == baseline_mtime
    # ERROR log present
    err_msgs = [r.message for r in caplog.records if r.levelno >= logging.ERROR]
    assert any("write failed" in m for m in err_msgs), (
        f"expected ERROR about write failure, got: {err_msgs}"
    )
    # Heartbeat reflects the failure (heartbeat write itself succeeded
    # because selective_boom only fails on the snapshot target)
    hb = json.loads((tmp_path / ".claude" / "snapshot_heartbeat.json").read_text())
    assert hb["last_error"] is not None
    assert "No space left" in hb["last_error"] or "OSError" in hb["last_error"]


