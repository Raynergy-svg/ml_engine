    """All 8 template sections render when source files are present."""
    _seed_minimal_state(tmp_path, halted=False)
    # Seed a ChangePackage so that section is non-empty.
    _write_json(tmp_path / ".claude" / "meta" / "changes" / "abc123.json", {
        "change_id": "abc123",
        "stage": "deployed_shadow",
        "incident": {"kind": "auto_halt_loss_streak"},
        "updated_at": "2026-05-10T15:00:00+00:00",
        "created_at": "2026-05-10T14:00:00+00:00",
    })
    # Seed a recent closed trade
    _write_json(tmp_path / "trained_data" / "trade_journal_rl.json", [{
        "trade_id": "live_1",
        "pair": "EUR_USD",
        "direction": "LONG",
        "outcome": "WIN",
        "pnl_pips": 12.4,
        "confidence": 0.71,
        "exit_reason": "tp_hit",
        # Use a "now-ish" close time inside the 24h window
        "close_time": _now_iso(),
    }])
    # Virtual trades line counter
    vt_path = tmp_path / "trained_data" / "virtual_trades.jsonl"
    vt_path.parent.mkdir(parents=True, exist_ok=True)
    vt_path.write_text("\n".join(['{"a":1}'] * 7) + "\n")

    writer = BriefingSnapshotWriter(project_root=tmp_path)
    assert writer.write_now(trigger="boot") is True

    snap = (tmp_path / ".claude" / "brain" / "snapshot.md").read_text()

    # Section 1: Header
    assert "# Buddy Snapshot —" in snap
    assert "HEAD:" in snap
    assert "halted:" in snap
    assert "last-write-trigger:" in snap
    # Section 2: Halt context (running branch)
    assert "## Halt context" in snap
    assert "running (mode=" in snap
    # Section 3: Recent trade outcomes
    assert "## Recent trade outcomes (24h)" in snap
    assert "EUR_USD" in snap
    assert "LONG" in snap
    # Section 4: Active alerts
    assert "## Active alerts" in snap
    # Section 5: Recent ChangePackages
    assert "## Recent ChangePackages" in snap
    assert "abc123" in snap
    assert "auto_halt_loss_streak" in snap
    # Section 6: Model freshness
    assert "## Model freshness" in snap
    # Section 7: Scan stats
    assert "## Scan stats" in snap
    assert "virtual_trades.jsonl lines" in snap
    assert "`7`" in snap  # 7 virtual trades lines
    # Section 8: Footer
    assert "generated by BriefingSnapshotWriter" in snap
