# ── Helpers ──────────────────────────────────────────────────────────

def _write_json(path: Path, payload: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload), encoding="utf-8")


def _seed_minimal_state(root: Path, halted: bool = False) -> None:
    """Drop a minimal viable .claude/state.json + heartbeat.json under root."""
    _write_json(root / ".claude" / "state.json", {
        "halted": halted,
        "mode": "demo",
        "scan_cycle_count": 42,
        "safe_restart": {"at": "2026-05-09T15:17:50Z", "reason": "operator_ctrl_r"},
    })
    _write_json(root / ".claude" / "heartbeat.json", {
        "pid": 12345,
        "ts_iso": "2026-05-10T18:57:33+00:00",
        "scanner_alive": True,
        "cycle_count": 42,
    })
    _write_json(root / ".claude" / "alert_state.json", {
        "active_alerts": [],
        "last_fired": {"consecutive_losses": 1778332923.0},
        "last_updated": "2026-05-10T18:57:02",
    })


