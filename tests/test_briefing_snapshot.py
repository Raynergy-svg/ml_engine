"""Tests for BriefingSnapshotWriter (Angle 1') — deterministic snapshot.md.

Hard rules per CLAUDE.md and .claude/rules/improvement.md:
- NO mocks. Real classes against real disk via tmp_path.
- briefing.md is NEVER touched. We assert that explicitly.
- Atomic-write semantics: failures must NOT leave partial files; heartbeat
  records the failure.
"""
from __future__ import annotations

