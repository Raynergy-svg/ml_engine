def test_corrupt_json_source_logged_not_crashed(tmp_path: Path, caplog) -> None:
    """Malformed state.json triggers WARN log but writer still succeeds."""
    bad_path = tmp_path / ".claude" / "state.json"
    bad_path.parent.mkdir(parents=True, exist_ok=True)
    bad_path.write_text("{this is not valid json", encoding="utf-8")

    writer = BriefingSnapshotWriter(project_root=tmp_path)
    with caplog.at_level(logging.WARNING, logger="src.scanner.automation.briefing_snapshot"):
        ok = writer.write_now(trigger="boot")

    assert ok is True
    snap_path = tmp_path / ".claude" / "brain" / "snapshot.md"
    assert snap_path.exists()
    # Verify a WARN-level message about the corrupt file was emitted
    warn_msgs = [r.message for r in caplog.records if r.levelno >= logging.WARNING]
    assert any("corrupt JSON" in m or "state.json" in m for m in warn_msgs), (
        f"expected WARN about corrupt state.json, got: {warn_msgs}"
    )


def test_diff_detection_skips_redundant_writes(tmp_path: Path) -> None:
    """Identical meaningful state on a 2nd write does NOT re-replace the file."""
    _seed_minimal_state(tmp_path)

    writer = BriefingSnapshotWriter(project_root=tmp_path)
    assert writer.write_now(trigger="boot") is True
    snap_path = tmp_path / ".claude" / "brain" / "snapshot.md"
    first_mtime = snap_path.stat().st_mtime

    # Sleep just enough that os.replace would change the mtime if it ran.
    time.sleep(0.05)
    assert writer.write_now(trigger="boot") is True

    second_mtime = snap_path.stat().st_mtime
    # The diff-and-write semantics should produce identical mtime — meaningful
    # state didn't change, the timestamps in `_DIFF_IGNORE_KEYS` are excluded
    # from the diff, and the trigger label itself is also ignored.
    assert second_mtime == first_mtime, (
        "diff detection should skip rewrite when meaningful state unchanged"
    )

    # Heartbeat should record the skip on the second call.
    hb = json.loads((tmp_path / ".claude" / "snapshot_heartbeat.json").read_text())
    assert hb.get("skipped") == "no_meaningful_change"


