def test_briefing_md_is_never_written(tmp_path: Path) -> None:
    """Hard invariant: this writer must not create or modify briefing.md.

    We pre-create a briefing.md with sentinel content and verify it survives.
    """
    briefing = tmp_path / ".claude" / "brain" / "briefing.md"
    briefing.parent.mkdir(parents=True, exist_ok=True)
    sentinel = "# Operator-curated briefing — DO NOT TOUCH\n"
    briefing.write_text(sentinel, encoding="utf-8")
    briefing_mtime = briefing.stat().st_mtime

    _seed_minimal_state(tmp_path, halted=True)
    writer = BriefingSnapshotWriter(project_root=tmp_path)
    assert writer.write_now(trigger="boot") is True
    # Multiple writes for good measure
    assert writer.maybe_write(cycle_count=12, every_n=12) is True

    # briefing.md is byte-identical and untouched
    assert briefing.read_text() == sentinel
    assert briefing.stat().st_mtime == briefing_mtime
    # snapshot.md exists separately
    assert (tmp_path / ".claude" / "brain" / "snapshot.md").exists()


def test_maybe_write_cadence_skips_off_cycles(tmp_path: Path) -> None:
    """maybe_write only fires on cycles divisible by every_n."""
    _seed_minimal_state(tmp_path)
    writer = BriefingSnapshotWriter(project_root=tmp_path)

    # Off-cycle: should be False, no file
    assert writer.maybe_write(cycle_count=7, every_n=12) is False
    assert not (tmp_path / ".claude" / "brain" / "snapshot.md").exists()

    # On-cycle: writes
    assert writer.maybe_write(cycle_count=12, every_n=12) is True
    assert (tmp_path / ".claude" / "brain" / "snapshot.md").exists()

    # every_n <= 0 disables
    assert writer.maybe_write(cycle_count=12, every_n=0) is False


